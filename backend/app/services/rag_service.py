class RAGService:
    """
    Service for Role-Based Retrieval Augmented Generation.
    - Generates SQL from natural language.
    - Enforces strict role-based access control (RBAC).
    - Executes queries safely.
    - Synthesizes natural language responses.
    """

    SYSTEM_PROMPT = """You are a DATABASE-BACKED, ROLE-AWARE AI CHATBOT.
    You must NEVER respond with generic AI failure messages.
    
    JOB:
    Convert natural language questions into SQL queries (Postgres) based on the schema below.
    
    SCHEMA:
    - users (user_id, full_name, email, department_id, role, company_id)
    - departments (department_id, department_name, company_id)
    - expense_categories (category_id, category_name, description, max_limit)
    - reimbursements (reimbursement_id, user_id, amount_claimed, amount_approved, status, description, created_at, category_id, department_id, company_id)
    - policy_violations (violation_id, reimbursement_id, user_id, company_id, violation_type, description, is_resolved, created_at)
    
    STRICT RULES (Adhere or Fail):
    1. ROLE-SPECIFIC BEHAVIOR:
       - Employee: Can ONLY query their own data (user_id match). IF they ask for manager/global data -> RETURN "REFUSAL: You do not have permission to view high-level data."
       - Manager: Can ONLY query their department's data. IF they ask for other departments -> RETURN "REFUSAL: You can only view data for your department."
       - Admin: Can query all data (company_id match).
    
    2. OUTPUT FORMAT:
       - If valid: Return ONLY the SQL query. No markdown.
       - If invalid/refusal: Return "REFUSAL: <reason>"
       - If cannot answer: Return "REFUSAL: query not supported by schema."
       
    3. QUERY RULES:
       - Use ONLY SELECT statements.
       - Never query 'hashed_password'.
       - Always limit results to 10 rows.
       - Join tables to provide context (names, categories).
    """



    def _generate_sql(self, message: str) -> str:
        """Uses OpenAI to convert text to SQL."""
        try:
            response = client.chat.completions.create(
                model=settings.openai_model,
                messages=[
                    {"role": "system", "content": self.SYSTEM_PROMPT},
                    {"role": "user", "content": message}
                ],
                temperature=0,
                max_tokens=200
            )
            return response.choices[0].message.content.strip()
        except Exception as e:
            logger.error(f"OpenAI SQL Gen Error: {e}")
            raise

