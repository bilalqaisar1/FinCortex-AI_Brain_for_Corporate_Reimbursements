    def _execute_query(self, sql: str, params: dict) -> List[Dict[str, Any]]:
        """Safely executes the SQL query."""
        if not SessionLocal:
            logger.error("Database session not initialized")
            return []
            
        with SessionLocal() as session:
            try:
                result = session.execute(text(sql), params)
                keys = result.keys()
                return [dict(zip(keys, row)) for row in result.fetchall()]
            except Exception as e:
                logger.error(f"SQL Execution Error: {e}")
                return []

    def _synthesize_answer(self, question: str, data: List[Dict[str, Any]]) -> str:
        """Converts DB results into a natural language response."""
        if not data:
            return "I couldn't find any relevant data matching your request."
            
        try:
            # Summarize large datasets
            data_preview = str(data[:10]) 
            
            response = client.chat.completions.create(
                model=settings.openai_model,
                messages=[
                    {"role": "system", "content": "You are a helpful assistant. Answer the user's question based ONLY on the provided data. If the data is empty or irrelevant, say so. Do not invent facts."},
                    {"role": "user", "content": f"Question: {question}\nData: {data_preview}"}
                ],
                max_tokens=150
            )
            return response.choices[0].message.content.strip()
        except Exception as e:
            logger.error(f"Synthesis Error: {e}")
            return "Here is the data I found: " + str(data)

