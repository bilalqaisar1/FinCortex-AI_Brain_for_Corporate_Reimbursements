    def query(self, user_id: str, message: str, role: str, department_id: Optional[int] = None, company_id: Optional[str] = None) -> Dict[str, Any]:
        
        # 1. Construct Role-Specific Prompt
        rbac_instruction = f"Context: User Role is '{role}'."
        params = {"company_id": company_id}
        
        if role == "admin":
             rbac_instruction += " Filter by 'company_id = :company_id'."
        elif role == "manager":
             rbac_instruction += " Filter by 'company_id = :company_id' AND 'department_id = :department_id'."
             params["department_id"] = department_id
        else: # employee
             rbac_instruction += " Filter by 'company_id = :company_id' AND 'user_id = :user_id'."
             params["user_id"] = user_id
             
        full_prompt = f"{self.SYSTEM_PROMPT}\n\n{rbac_instruction}\n\nQuestion: {message}"
        
        # 2. Generate and Execute
        try:
            response = client.chat.completions.create(
                model=settings.openai_model,
                messages=[{"role": "system", "content": full_prompt}],
                temperature=0
            )
            content = response.choices[0].message.content.strip()
            
            # Check for Refusal
            if content.startswith("REFUSAL:"):
                 return {"response": content.replace("REFUSAL:", "").strip()}

            sql_query = content.replace("```sql", "").replace("```", "").strip()
            
            # Simple validation
            if "delete" in sql_query.lower() or "update" in sql_query.lower() or "drop" in sql_query.lower():
                 return {"response": "I cannot perform modification actions."}
            
            results = self._execute_query(sql_query, params)
            
            # 3. Synthesize Answer
            answer = self._synthesize_answer(message, results)
            
            return {"response": answer, "sources": results}
            
        except Exception as e:
            logger.error(f"RAG Pipeline Error: {e}")
            # Strict error handling as requested
            return {"response": "An internal error occurred while processing your request. Please contact support if this persists."}

